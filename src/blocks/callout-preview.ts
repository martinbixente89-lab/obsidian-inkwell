import { MarkdownPostProcessorContext, Plugin, setIcon } from 'obsidian';
import { parseCalloutMetadata } from './callout-parser';

/**
 * Resolves the Lucide icon name for a given callout type, matching Inkwell's visual widgets.
 */
export function resolveCalloutIcon(type: string): string {
	const lower = type.toLowerCase();
	if (lower === 'warning' || lower === 'caution' || lower === 'attention') {
		return 'alert-triangle';
	}
	if (lower === 'tip' || lower === 'hint' || lower === 'important') {
		return 'lightbulb';
	}
	if (lower === 'info' || lower === 'todo') {
		return 'info';
	}
	if (lower === 'check' || lower === 'success' || lower === 'done') {
		return 'check-circle';
	}
	return 'message-square';
}

/**
 * Detects whether a rendered callout in Reading Mode has a genuine user-defined title
 * vs an automatic default title generated by Obsidian (e.g. "Note").
 */
export function detectCalloutCustomTitle(
	calloutEl: HTMLElement,
	ctx?: MarkdownPostProcessorContext,
): { hasCustomTitle: boolean; title: string } {
	const calloutType = (calloutEl.getAttribute('data-callout') ?? 'note').toLowerCase();

	// 1. If MarkdownPostProcessorContext has section info, inspect raw Markdown source
	if (ctx && typeof ctx.getSectionInfo === 'function') {
		const info = ctx.getSectionInfo(calloutEl);
		if (info && info.text) {
			const lines = info.text.split('\n').slice(info.lineStart, info.lineEnd + 1);
			for (const line of lines) {
				const match = /^\s*(?:>\s*)+\[!([a-zA-Z0-9_-]+)(?:\|[^\]]*)?\]([+-])?(?:[ \t]+(.*))?$/i.exec(
					line,
				);
				if (match && match[1]?.toLowerCase() === calloutType) {
					const rawTitle = (match[3] ?? '').trim();
					if (rawTitle.length > 0) {
						return { hasCustomTitle: true, title: rawTitle };
					} else {
						return { hasCustomTitle: false, title: '' };
					}
				}
			}
		}
	}

	// 2. Fallback: inspect the rendered .callout-title-inner text
	const titleInner = calloutEl.querySelector('.callout-title-inner');
	const text = titleInner?.textContent?.trim() ?? '';
	// If the text is empty or equal to the callout type (e.g. "Note", "NOTE"), it is the auto-generated title.
	if (text === '' || text.toLowerCase() === calloutType) {
		return { hasCustomTitle: false, title: '' };
	}

	return { hasCustomTitle: true, title: text };
}

/**
 * Harmonizes the presentation of callouts (encadrés) in Reading Mode (.markdown-rendered)
 * so that they strictly match the compact visual styling used in Live Preview:
 * - Grey background (var(--background-secondary-alt))
 * - 8px border radius and 1px border
 * - Purple message-square icon (var(--interactive-accent))
 * - Single-story flex row layout with icon on left and content on right
 * - Automatic "Note" header is hidden while user-defined custom titles are preserved.
 */
export function harmonizeCalloutPreview(
	rootEl: HTMLElement = document.body,
	ctx?: MarkdownPostProcessorContext,
): void {
	const calloutElements: HTMLElement[] = [];
	if (rootEl.matches?.('.callout[data-callout="note"]')) {
		calloutElements.push(rootEl);
	}
	rootEl.querySelectorAll?.('.callout[data-callout="note"]').forEach((node) => {
		if (node instanceof HTMLElement) {
			calloutElements.push(node);
		}
	});

	for (const calloutEl of calloutElements) {
		const calloutType = calloutEl.getAttribute('data-callout') ?? 'note';
		const { hasCustomTitle, title } = detectCalloutCustomTitle(calloutEl, ctx);

		calloutEl.classList.add('inkwell-callout-harmonized');
		if (hasCustomTitle) {
			calloutEl.classList.add('has-custom-title');
			calloutEl.classList.remove('is-compact-default');
		} else {
			calloutEl.classList.add('is-compact-default');
			calloutEl.classList.remove('has-custom-title');
		}

		// Ensure the icon matches Inkwell's visual icon (message-square for NOTE)
		let iconEl = calloutEl.querySelector('.callout-icon');
		if (iconEl instanceof HTMLElement) {
			setIcon(iconEl, resolveCalloutIcon(calloutType));
			iconEl.classList.add('inkwell-visual-callout-icon');
		}

		// Restructure DOM into a single flex row: icon on left, content column on right
		let contentCol = calloutEl.querySelector(':scope > .inkwell-callout-content-col');
		if (!contentCol) {
			contentCol = document.createElement('div');
			contentCol.className = 'inkwell-callout-content-col';

			const titleEl = calloutEl.querySelector(':scope > .callout-title');
			iconEl =
				calloutEl.querySelector(':scope > .callout-title > .callout-icon') ??
				calloutEl.querySelector(':scope > .callout-icon');
			const titleInnerEl =
				calloutEl.querySelector(':scope > .callout-title > .callout-title-inner') ??
				calloutEl.querySelector(':scope > .callout-title-inner');
			const contentEl = calloutEl.querySelector(':scope > .callout-content');

			if (iconEl && titleEl && titleEl.contains(iconEl)) {
				calloutEl.insertBefore(iconEl, titleEl);
			}

			if (titleInnerEl) {
				contentCol.appendChild(titleInnerEl);
			}

			if (contentEl) {
				contentCol.appendChild(contentEl);
			}

			if (titleEl && calloutEl.contains(titleEl)) {
				titleEl.remove();
			}

			calloutEl.appendChild(contentCol);
		}

		// Apply custom individual visual styles (bg, border on/off, border color)
		const metaStr = calloutEl.getAttribute('data-callout-metadata');
		const customStyle = parseCalloutMetadata(metaStr ?? undefined);

		const bg = customStyle?.bg || '';
		let border = '';
		if (customStyle?.border === false) {
			border = 'none';
		} else if (customStyle?.borderColor) {
			border = `1px solid ${customStyle.borderColor}`;
		}

		calloutEl.setCssProps({
			'--inkwell-callout-bg': bg,
			'--inkwell-callout-border': border,
		});

		// If custom title was extracted from Markdown, ensure titleInnerEl text is up to date
		if (hasCustomTitle && title) {
			const titleInner = contentCol.querySelector('.callout-title-inner');
			if (titleInner && titleInner.textContent !== title) {
				titleInner.textContent = title;
			}
		}
	}
}

/**
 * Registers observers and event hooks to ensure callout presentation in Reading Mode
 * is continuously harmonized even during scrolling or dynamic section recycling.
 */
export function registerCalloutPreviewManager(plugin: Plugin): void {
	// 1. Standard markdown post-processor for initial render of sections
	plugin.registerMarkdownPostProcessor((el, ctx) => {
		harmonizeCalloutPreview(el, ctx);
	});

	// 2. DOM MutationObserver to detect sections brought into DOM via reading view virtual scrolling
	const observer = new MutationObserver((mutations) => {
		let hasCallouts = false;
		for (const m of mutations) {
			for (let i = 0; i < m.addedNodes.length; i++) {
				const node = m.addedNodes[i];
				if (
					node instanceof HTMLElement &&
					(node.matches('.callout[data-callout="note"]') ||
						node.querySelector('.callout[data-callout="note"]'))
				) {
					hasCallouts = true;
					break;
				}
			}
			if (hasCallouts) break;
		}
		if (hasCallouts) {
			harmonizeCalloutPreview(document.body);
		}
	});

	observer.observe(document.body, { childList: true, subtree: true });
	plugin.register(() => observer.disconnect());

	// 3. Workspace events
	plugin.registerEvent(
		plugin.app.workspace.on('layout-change', () => {
			harmonizeCalloutPreview(document.body);
		}),
	);

	plugin.registerEvent(
		plugin.app.workspace.on('active-leaf-change', () => {
			harmonizeCalloutPreview(document.body);
		}),
	);

	plugin.registerEvent(
		plugin.app.workspace.on('file-open', () => {
			harmonizeCalloutPreview(document.body);
		}),
	);

	// 4. Capture scroll events to harmonize as virtualized sections enter viewport
	plugin.registerDomEvent(
		window,
		'scroll',
		() => {
			harmonizeCalloutPreview(document.body);
		},
		true,
	);
}
